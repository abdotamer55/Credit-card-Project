import sys
from pathlib import Path
import streamlit as st
import pandas as pd
from assets.style import load_css

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from utils.common import load_data, train_segmentation_model

st.set_page_config(
    page_title="Visualizations | Credit Card Segmentation",
    page_icon="📊",
    layout="wide",
)

load_css()

st.title("📊 Project Visualizations")
st.caption("Interactive gallery of the visual outputs generated by the clustering analysis.")

VIS_DIR = ROOT / "Visulization"

try:
    bundle = train_segmentation_model()
    df = bundle["labeled"]
except Exception as e:
    st.error(str(e))
    st.stop()

st.markdown("## 📌 Clustering Snapshot")

c1, c2, c3, c4 = st.columns(4)
c1.metric("Customers", f"{len(df):,}")
c2.metric("Clusters", "4")
c3.metric("PCA Components", "13")
c4.metric("2D PCA Variance", "49.6%")

# -----------------------------
# Dynamic cluster summary
# -----------------------------
st.markdown("## 👥 Segment Distribution")

counts = df["Cluster"].value_counts().sort_index()
st.bar_chart(counts.rename("Customers"))

summary = pd.DataFrame({
    "Cluster": counts.index,
    "Segment": [bundle["labeled"].loc[bundle["labeled"]["Cluster"].eq(i), "Cluster_Name"].iloc[0] for i in counts.index],
    "Customers": counts.values,
})
summary["Share %"] = (summary["Customers"] / len(df) * 100).round(1)
st.dataframe(summary, use_container_width=True)

# -----------------------------
# Saved notebook visualizations
# -----------------------------
st.markdown("## 🖼️ Notebook Visualizations")

if not VIS_DIR.exists():
    st.warning(f"Visualization folder not found: {VIS_DIR}")
    st.stop()

image_files = sorted(VIS_DIR.glob("*.png"))

if not image_files:
    st.info("No PNG visualizations were found in the Visulization folder.")
    st.stop()

labels = {
    "01_feature_distribution_histograms.png": "Feature Distribution Histograms",
    "02_correlation_heatmap.png": "Correlation Heatmap",
    "03_purchase_behavior_boxplots.png": "Purchase Behavior Boxplots",
    "04_cash_advance_boxplots.png": "Cash Advance Boxplots",
    "05_full_payment_distribution.png": "Full Payment Distribution",
    "06_tenure_distribution.png": "Tenure Distribution",
    "07_scatter_plot_matrix.png": "Customer Relationship Scatter Plots",
    "08_PCAanalysis.png": "PCA Analysis",
    "09_K_value_evaluation.png": "K Value Evaluation",
    "10_KMeansdbscan_clustering_visualization.png": "K-Means Clustering Visualization",
    "15_model_evaluation.png": "Model Evaluation",
    "16_cluster_distribution_and_radar.png": "Cluster Distribution & Radar Chart",
    "17_cluster_feature_comparison_bar_chart.png": "Cluster Feature Comparison",
    "18_cluster_feature_heatmap.png": "Cluster Feature Heatmap",
    "19_tenure_distribution_by_cluster.png": "Tenure Distribution by Cluster",
}

available = [f for f in image_files if f.name in labels]
options = {labels.get(f.name, f.stem): f for f in available}

selected = st.selectbox("Choose a visualization", list(options.keys()))

st.image(
    str(options[selected]),
    caption=selected,
    use_container_width=True,
)

# -----------------------------
# Key interpretation
# -----------------------------
st.markdown("## 🧠 Key Model Visuals")

cols = st.columns(2)

for idx, filename in enumerate([
    "09_K_value_evaluation.png",
    "10_KMeansdbscan_clustering_visualization.png",
    "16_cluster_distribution_and_radar.png",
    "18_cluster_feature_heatmap.png",
]):
    path = VIS_DIR / filename
    if path.exists():
        with cols[idx % 2]:
            st.image(str(path), caption=labels.get(filename, filename), use_container_width=True)